-- One-time migration for the original, unpartitioned TrackFlow events table.
-- Run in a maintenance window: this takes an ACCESS EXCLUSIVE lock and copies
-- all event rows in one transaction. A failure rolls the entire migration back.
BEGIN;

LOCK TABLE events IN ACCESS EXCLUSIVE MODE;
ALTER TABLE events RENAME TO events_unpartitioned_migration;
ALTER TABLE events_unpartitioned_migration
    RENAME CONSTRAINT events_pkey TO events_unpartitioned_migration_pkey;
ALTER SEQUENCE events_id_seq RENAME TO events_unpartitioned_migration_id_seq;

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    session_id BIGINT REFERENCES sessions(id),
    event_type VARCHAR(50) NOT NULL,
    properties JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);

DO $$
DECLARE
    first_month DATE;
    last_month DATE;
    partition_month DATE;
    next_month DATE;
BEGIN
    SELECT
        date_trunc('month', MIN(created_at) AT TIME ZONE 'UTC')::DATE,
        date_trunc('month', MAX(created_at) AT TIME ZONE 'UTC')::DATE
    INTO first_month, last_month
    FROM events_unpartitioned_migration;

    IF first_month IS NULL THEN
        first_month := date_trunc('month', NOW() AT TIME ZONE 'UTC')::DATE;
        last_month := first_month;
    END IF;

    first_month := LEAST(
        first_month,
        date_trunc('month', NOW() AT TIME ZONE 'UTC')::DATE
    );
    last_month := GREATEST(
        last_month,
        (date_trunc('month', NOW() AT TIME ZONE 'UTC')::DATE + INTERVAL '2 months')::DATE
    );

    partition_month := first_month;
    WHILE partition_month <= last_month LOOP
        next_month := (partition_month + INTERVAL '1 month')::DATE;
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF events FOR VALUES FROM (%L) TO (%L)',
            'events_' || to_char(partition_month, 'YYYY_MM'),
            partition_month::TIMESTAMP AT TIME ZONE 'UTC',
            next_month::TIMESTAMP AT TIME ZONE 'UTC'
        );
        partition_month := next_month;
    END LOOP;
END;
$$;

INSERT INTO events (id, user_id, session_id, event_type, properties, created_at)
SELECT id, user_id, session_id, event_type, COALESCE(properties, '{}'::JSONB),
       COALESCE(created_at, NOW())
FROM events_unpartitioned_migration;

SELECT setval(
    pg_get_serial_sequence('events', 'id'),
    COALESCE(MAX(id), 1),
    MAX(id) IS NOT NULL
)
FROM events;

DROP TABLE events_unpartitioned_migration;

CREATE OR REPLACE FUNCTION ensure_event_partitions(months_ahead INTEGER DEFAULT 3)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    month_offset INTEGER;
    partition_month DATE;
    next_month DATE;
BEGIN
    IF months_ahead < 3 OR months_ahead > 24 THEN
        RAISE EXCEPTION 'months_ahead must be between 3 and 24';
    END IF;

    PERFORM pg_advisory_xact_lock(1413567052, 1);

    FOR month_offset IN 0..(months_ahead - 1) LOOP
        partition_month :=
            (date_trunc('month', NOW() AT TIME ZONE 'UTC')::DATE
                + month_offset * INTERVAL '1 month')::DATE;
        next_month := (partition_month + INTERVAL '1 month')::DATE;

        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS %I PARTITION OF events FOR VALUES FROM (%L) TO (%L)',
            'events_' || to_char(partition_month, 'YYYY_MM'),
            partition_month::TIMESTAMP AT TIME ZONE 'UTC',
            next_month::TIMESTAMP AT TIME ZONE 'UTC'
        );
    END LOOP;
END;
$$;

SELECT ensure_event_partitions(3);

CREATE INDEX events_user_created_at_idx
    ON events (user_id, created_at DESC);
CREATE INDEX events_created_at_idx
    ON events (created_at);

CREATE TABLE events_archive (
    id BIGINT NOT NULL,
    user_id INTEGER NOT NULL,
    session_id BIGINT,
    event_type VARCHAR(50) NOT NULL,
    properties JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    archived_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id, created_at)
);

CREATE INDEX events_archive_user_created_at_idx
    ON events_archive (user_id, created_at DESC);
CREATE INDEX events_archive_created_at_idx
    ON events_archive (created_at);

COMMIT;
